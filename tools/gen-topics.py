def pick_formulas(title, track, detail, want=5):
    """挑出对这条素材最适用的几条公式。

    为什么不是 10 条全出：10 个候选太多，用户选不过来，而且一半会明显不合素材。
    按关键词判断素材特征，命中越多的公式排越前，取前 want 条。

    这是**粗筛**，判不准也没关系 —— 出的是「建议从这几个角度写标题」，
    真正的句子由 Agent 按结构重写。
    """
    t = title or ""
    scores = {}
    for fid, name, when, how in TITLE_FORMULAS:
        s = 0
        # 03 熟悉事+意外结果：标题里有转折/反差信号
        if fid == "03":
            if re.search(r"却|但|反而|竟然|居然|没想到|不是.*是|已经|都", t): s += 3
            if re.search(r"不够|不够烧|反而|越.*越", t): s += 2
        # 02 数字+清单
        if fid == "02":
            if re.search(r"\d+\s*(个|条|种|款|步|招|件)", t): s += 4
            if re.search(r"清单|合集|盘点|大全|指南|模板", t): s += 3
        # 07 普通人+不寻常结果
        if fid == "07":
            if re.search(r"\d+\s*(万|亿|倍|天|年|个月|小时)", t): s += 2
            if re.search(r"涨粉|赚|做成|做到|完成|逆袭|爆红|出圈", t): s += 3
            if re.search(r"我|他|她|一个|这位|那个", t): s += 1
        # 04 折磨人的小动作
        if fid == "04":
            if re.search(r"内耗|焦虑|纠结|反复|忍不住|睡不着|复盘|后悔", t): s += 3
            if re.search(r"习惯|总是|老是|每次|天天", t): s += 2
        # 05 羡慕状态+共同点
        if fid == "05":
            if re.search(r"从不|那些|这类人|都有|共性|共同点", t): s += 3
            if re.search(r"厉害|优秀|靠谱|自律|成功", t): s += 2
        # 06 熟悉物+没想过的问题
        if fid == "06":
            if re.search(r"[？?]", t): s += 2
            if re.search(r"怎么|如何|为什么|是什么", t): s += 1
        # 08 小钱+麻烦
        if fid == "08":
            if re.search(r"\d+\s*(元|块|毛)", t): s += 3
            if re.search(r"便宜|省钱|好用|神器|帮了大忙|解决", t): s += 2
        # 09 时间锚
        if fid == "09":
            if re.search(r"跨年|春节|过年|开学|年终|中秋|国庆|母亲节|父亲节|元旦|月初|月底", t): s += 4
            if re.search(r"文案|准备|清单|素材|发什么|说什么", t): s += 2
        # 10 一句干脆的判断
        if fid == "10":
            if re.search(r"本质|就是|不过是|说到底|其实|真相", t): s += 2
            if len(t) <= 16: s += 1
        # 01 场景+话术
        if fid == "01":
            if re.search(r"怎么回|怎么说|怎么拒绝|怎么开口|高情商|话术", t): s += 4
            if re.search(r"做客|领导|客户|亲戚|朋友|同事", t): s += 1

        if s > 0:
            scores[(fid, name, when, how)] = s

    if not scores:
        # 一条都没命中：给最通用的三条（03/06/07 适合任何热点）
        return [f for f in TITLE_FORMULAS if f[0] in ("03", "06", "07")][:want]

    ranked = sorted(scores.items(), key=lambda kv: -kv[1])
    picked = [k for k, _ in ranked][:want]
    # 不足 want 条就补通用公式，保证总有 5 个角度可选
    if len(picked) < want:
        for f in TITLE_FORMULAS:
            if f not in picked:
                picked.append(f)
            if len(picked) >= want:
                break
    return picked


def gen_titles(title, track, detail):
    """按 10 条爆款公式生成候选标题。

    **2026-11-18 重写**。上一版是机械改写原标题（去前缀、提数字、加悬念尾巴），
    产出的是「11，如何看待 月 7 日…」这类拼接残句 —— 那不是创作，是字符串操作。

    现在改成：先判断这条素材适用哪几条公式，再把**公式的结构要求**交给 Agent 重写。
    真正的句子由 Agent 写，这里负责「告诉它按什么结构写」+ 「写完怎么判不合格」。

    返回值里每项带 formula（公式编号+名字）和 how（结构要求），
    调用方（topic-pipeline 的指令、界面的候选列表）都按这个展示。
    """
    out = []
    boosts = detail.get("爆点词") or []

    # 1) 直述型：去掉平台口吻的前缀，至少保住一个「原样但干净」的版本
    t = re.sub(r"^(如何看待|如何评价|怎么看待|为何|为什么)\s*", "", title).strip()
    t = t.rstrip("？?。 ")
    if len(t) >= 8:
        out.append({"title": t, "style": "直述", "formula": "", "how": "原样保留（去掉平台口吻）"})

    # 2) 挑适用公式，每个公式产出一条「结构要求」而不是拼好的句子
    for fid, name, when, how in pick_formulas(title, track, detail, want=5):
        out.append({
            "title": "",                      # 空：由 Agent 按结构重写
            "style": f"{fid} {name}",
            "formula": fid,
            "how": how,
            "when": when,
        })

    return out


def title_lint(text):
    """标题体检：返回问题列表（空 = 通过）。

    **只提示不阻断** —— 标题是创意活，硬拦会误杀好标题。
    但问题要具体指出来，不能只说「不合格」。

    ⚠️ 规则是**用 10W+ 原文标题校准过的**（2026-11-18）。
    第一版写了 6 条检查，拿那篇文章里的 10 个示例标题一测，
    误报 4 个、漏抓 3 个 —— 说明规则本身是错的。校准后的取舍：

      · 「没有具体元素」这条**删了**：`学习的本质：极致的重复` 是那篇文章
        明确推荐的 10 号公式范例，它没有人物没有数字，但它是好标题。
        「必须有具体元素」是我自己加的臆断，不是原文的规律。
      · 「三个以上并列」只在**全是名词短语**时才判（`营收X、股价Y、SEC调查`
        这种堆砌），`去别人家做客，对方说"…"，别说"…"，高情商这样回`
        虽然逗号多，但它是完整叙事，不该报。
      · 「不是X是Y」要判，但**只判结尾是抽象词的**那种。
        `她知道身世那天，第一反应是感动` 的问题不是结构，是「感动」这个抽象词。
    """
    s = (text or "").strip()
    problems = []
    if not s:
        return ["标题为空"]

    # ① 抽象词收尾 —— 这是那篇文章里最硬的规律（四段不同内容反复强调同一件事）
    tail6 = s[-6:]
    for w in ABSTRACT_TAIL:
        if w in tail6:
            problems.append("结尾是抽象词「%s」——读者看完等于没看，换成具体的人/事/动作" % w)
            break

    # ② 结论式：只判「不是X，是Y」且 Y 是抽象判断
    m = re.search(r"不是.{1,14}[，,]\s*(?:是|而是)(.{2,10})$", s)
    if m and any(w in m.group(1) for w in ABSTRACT_TAIL):
        problems.append("「不是X，是Y」把答案说了，而且Y是抽象判断——改成只给反常现象")

    # ③ 纯抽象主语：只在**整句没有具体元素**时才判。
    #    单看开头会误伤（「学习的本质：极致的重复」开头就是抽象词，但它是好标题）。
    ABSTRACT_SUBJECT = r"^(可读性|认知|逻辑|本质|格局|心态|效率|价值|意义|思维|人性|商业|内容|产品)"
    has_concrete = bool(re.search(
        r"我|你|他|她|这位|那个|一个|有人|网友|员工|车主|家长|学生|孩子|老人|"
        r"医生|老师|老板|同事|司机|乘客|市民|顾客|人们|大家"
        r"|\d|[一二三四五六七八九十百千万亿两半几]"
        r"|[「『\"“]"
        r"|[A-Za-z]{2,}"
        r"|腾讯|阿里|百度|字节|抖音|微信|华为|小米|英伟达|谷歌|苹果|微软|特斯拉|比亚迪"
        r"|深圳|上海|北京|杭州|哈尔滨|广东|中国|美国|日本|俄罗斯|乌克兰|以色列|伊朗"
        r"|大学|医院|法院|警方|政府|公司|平台|机场|车站|学校", s))
    if re.match(ABSTRACT_SUBJECT, s) and not has_concrete:
        problems.append("开头是抽象名词，整句又没有具体的人/事——无法代入")

    # ④ 抽象隐喻：「背后是两个不同的大脑」——把具体东西换成抽象名词，
    #    读者要猜，而好标题不需要猜。
    if ABSTRACT_METAPHOR.search(s):
        problems.append("用了抽象隐喻（「是X个大脑/镜子/江湖」）——换成具体的人在做什么")

    # ⑤ 并列事实堆砌：只在**全是短名词短语**时判。
    #    `营收 1158 亿超预期、股价连跌六周、SEC 启动调查` → 三段都是名词短语，判
    #    `去别人家做客，对方说"…"，别说"…"，高情商这样回` → 是完整叙事，不判
    parts = [p.strip() for p in re.split(r"[、，,]", s) if p.strip()]
    if len(parts) >= 3 and all(len(p) <= 14 for p in parts) \
            and not re.search(r"说|问|回|做|走|来|去|给|让|把|被|了|着|过", s):
        problems.append("三个以上并列短语，没有一个动作或人——读者记不住")

    # ⑥ 空问句：只有「为什么XX」这种没有具体对象的才判
    if EMPTY_WHY.match(s.rstrip("？?")):
        problems.append("空问句——「为什么XX」后面要跟具体对象，否则读者不知道在问什么")

    # ⑦ 元叙述：标题在评价自己的内容，而不是直接给内容（2026-11-18 加）。
    #    `外交部写的是管控分歧，这四个字值得看清` —— 它不违反上面任何一条，
    #    但「值得看清」是吆喝，「那四个字」是什么却没说。把内容摆出来，让读者自己判断。
    if META_NARRATION.search(s):
        problems.append("元叙述（「值得看清」「这四个字」「别不当回事」）——"
                        "标题在吆喝而不是给内容，把那句话直接摆出来")

    return problems


